const path=(coordinates:Coordinate[],closed=false)=>{
  const points=coordinates.map(([lat,lng])=>project(lat,lng,"sweden"));
  return points.length?`M${points[0].x.toFixed(2)} ${points[0].y.toFixed(2)} ${points.slice(1).map(point=>`L${point.x.toFixed(2)} ${point.y.toFixed(2)}`).join(" ")}${closed?" Z":""}`:"";
};

export const SWEDEN_LAKE_PATH=lakes.map(coordinates=>path(coordinates,true)).join(" ");
export const SWEDEN_RIVER_PATH=rivers.map(coordinates=>path(coordinates)).join(" ");
